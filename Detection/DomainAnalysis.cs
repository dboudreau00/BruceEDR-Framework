    /// <summary>
    /// Score one DNS name. Never throws and never returns null for any input, including
    /// null, empty, whitespace, an IP literal, a name with empty labels, or a megabyte of
    /// hostile junk -- a name arriving from a DNS monitor is untrusted data and must not
    /// be able to take down the detection thread.
    /// </summary>
    public static DomainVerdict Analyze(string domain)
    {
        string raw = domain ?? "";
        bool truncated = raw.Length > MaxAnalysedLength;
        if (truncated) raw = raw[..MaxAnalysedLength];

        string norm = NormalizeName(raw);
        if (norm.Length == 0)
        {
            return new DomainVerdict
            {
                Explanation = "empty or unusable name; nothing to analyse."
            };
        }

        // An IP literal is not a domain. Scoring 203.0.113.5 for "pronounceability" would
        // produce a meaningless number that callers would then threshold on.
        if (IPAddress.TryParse(norm, out _))
        {
            return new DomainVerdict
            {
                Domain = norm,
                LabelCount = 0,
                RegistrableDomain = norm,
                Explanation = "literal IP address, not a domain name; DGA and tunnel heuristics do not apply."
            };
        }

        string[] labels = norm.Split('.', StringSplitOptions.RemoveEmptyEntries);
        if (labels.Length == 0)
        {
            return new DomainVerdict
            {
                Domain = norm,
                Explanation = "name contains no usable labels."
            };
        }

        string registrable = Registrable(labels);
        int suffixLabels = Math.Max(0, CountLabels(registrable) - 1);
        int nameIndex = Math.Max(0, labels.Length - suffixLabels - 1);

        // Default subject: the registrable name label, the part the registrant chose.
        string scored = labels[nameIndex];
        double best = ScoreLabel(scored);

        // ... but a family that registers "a1b2c3xyz.duckdns.org" controls only the
        // LEFT-most label; scoring the registrable name would judge the provider's brand
        // and miss the payload entirely. So every operator-chosen label long enough to
        // carry signal is scored and the worst one wins. The cost is more exposure to
        // long machine-generated CDN subdomains, which is the dominant false positive here.
        for (int i = 0; i < nameIndex; i++)
        {
            if (labels[i].Length < MinScannedLabelLength) continue;
            double s = ScoreLabel(labels[i]);
            if (s > best) { best = s; scored = labels[i]; }
        }

        double entropy = Entropy(scored);
        double consonantRatio = ConsonantRatio(scored);
        double digitRatio = DigitRatio(scored);
        bool likelyDga = best >= DgaThreshold && scored.Length >= MinDgaLabelLength;

        bool punycode = false;
        foreach (var l in labels)
            if (l.StartsWith("xn--", StringComparison.Ordinal)) { punycode = true; break; }

        bool dynamicDns = IsDynamicDnsProvider(norm);
        bool tunnel = LooksLikeTunnel(labels, suffixLabels, out string tunnelWhy);

        var why = new List<string>(6);
        if (likelyDga)
            why.Add($"label '{scored}' scores {best.ToString("0.00", CultureInfo.InvariantCulture)} on the DGA heuristic " +
                    $"(entropy {entropy.ToString("0.00", CultureInfo.InvariantCulture)} bits/char, " +
                    $"{(int)Math.Round(consonantRatio * 100)}% consonants, " +
                    $"{(int)Math.Round(digitRatio * 100)}% digits)");
        else
            why.Add($"label '{scored}' scores {best.ToString("0.00", CultureInfo.InvariantCulture)}, below the " +
                    $"{DgaThreshold.ToString("0.00", CultureInfo.InvariantCulture)} DGA threshold");

        if (dynamicDns) why.Add($"registrable domain '{registrable}' is a dynamic-DNS or tunnelling provider (also used legitimately)");
        if (punycode) why.Add("contains an xn-- (IDNA) label, so a homograph of a known brand is possible");
        if (tunnel) why.Add(tunnelWhy);
        if (truncated) why.Add("oversized name was truncated before analysis");

        return new DomainVerdict
        {
            Domain = norm,
            DgaScore = Math.Round(best, 3),
            LikelyDga = likelyDga,
            IsDynamicDns = dynamicDns,
            IsPunycode = punycode,
            LabelCount = labels.Length,
            Entropy = Math.Round(entropy, 3),
            ConsonantRatio = Math.Round(consonantRatio, 3),
            DigitRatio = Math.Round(digitRatio, 3),
            RegistrableDomain = registrable,
            Tld = labels[^1],
            Explanation = string.Join("; ", why) + ".",
            LooksLikeDnsTunnel = tunnel
        };
    }

    /// <summary>
    /// Name plus public suffix (<c>example.co.uk</c>), used to group subdomains that share
    /// an owner. Best effort against the hand-maintained suffix subset described in the
    /// class remarks; returns the input normalised when it has one or two labels.
    /// </summary>
    public static string RegistrableDomain(string domain)
    {
        string norm = NormalizeName(domain ?? "");
        if (norm.Length == 0) return "";
        if (IPAddress.TryParse(norm, out _)) return norm;
        var labels = norm.Split('.', StringSplitOptions.RemoveEmptyEntries);
        return labels.Length == 0 ? "" : Registrable(labels);
    }

    /// <summary>
    /// True when the name is, or sits beneath, a known dynamic-DNS / free-subdomain /
    /// developer-tunnel provider. Matching is on the suffix boundary, so
    /// <c>evilduckdns.org</c> does not match <c>duckdns.org</c>.
    /// </summary>
    public static bool IsDynamicDnsProvider(string domain)
    {
        string norm = NormalizeName(domain ?? "");
        if (norm.Length == 0) return false;

        // Walk the suffixes of the name rather than the provider list, so cost is bounded
        // by label count (at most ~127) instead of by the size of the provider table.
        if (DynamicDnsSuffixes.Contains(norm)) return true;
        int idx = 0;
        while (true)
        {
            int dot = norm.IndexOf('.', idx);
            if (dot < 0 || dot + 1 >= norm.Length) return false;
            if (DynamicDnsSuffixes.Contains(norm[(dot + 1)..])) return true;
            idx = dot + 1;
        }
    }

