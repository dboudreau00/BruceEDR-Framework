    /// <summary>
    /// Lower-cases, trims surrounding whitespace and strips the FQDN root dot. A BOM and a
    /// zero-width space are trimmed too, because both are used to smuggle a visually
    /// identical hostname past a naive string comparison; they are written as numeric
    /// escapes so the source stays legible and cannot be mangled by a re-encode.
    /// </summary>
    private static string NormalizeName(string domain)
    {
        string s = domain.Trim().Trim(InvisibleTrimChars);
        // A trailing dot is the DNS root and carries no meaning for these heuristics;
        // leaving it on would silently create an empty final label.
        while (s.Length > 0 && s[^1] == '.') s = s[..^1];
        return s.ToLowerInvariant();
    }

    private static int CountLabels(string s)
    {
        if (s.Length == 0) return 0;
        int n = 1;
        foreach (char c in s) if (c == '.') n++;
        return n;
    }

    private static string Registrable(string[] labels)
    {
        if (labels.Length <= 2) return string.Join('.', labels);
        string lastTwo = labels[^2] + "." + labels[^1];
        return MultiPartSuffixes.Contains(lastTwo)
            ? labels[^3] + "." + lastTwo
            : lastTwo;
    }

    /// <summary>
    /// Composite DGA score for one label, in 0..1.
    ///
    /// EXACT FORMULA:
    ///   bigram    = clamp01((1.95 - meanLog10BigramWeight) / 1.10)
    ///   entropy   = clamp01((H - 3.0) / 1.20)                  H in bits/char
    ///   consonant = clamp01((longestConsonantRun - 3) / 3.0)
    ///   digit     = clamp01((digitRatio - 0.10) / 0.30)
    ///   length    = clamp01((len - 7) / 5.0)
    ///   score     = 0.42*bigram + 0.14*entropy + 0.14*consonant + 0.14*digit + 0.16*length
    ///
    /// WHY BIGRAMS DOMINATE (0.42): at the 8-15 character lengths that matter, Shannon
    /// entropy is nearly useless as a discriminator, because a short label of distinct
    /// characters is at its entropy ceiling whether it spells "microsoft" or "kq3v9zwx".
    /// Pronounceability, measured as bigram plausibility, is the feature that actually
    /// separates them; entropy is kept only as a weak corroborator. The remaining terms
    /// are shape priors: DGA output tends to be longish, consonant-heavy and digit-salted.
    ///
    /// Hyphens and digits terminate consonant runs and are skipped when forming bigram
    /// pairs, so <c>s3-us-west-2</c> is not punished for being unpronounceable.
    /// </summary>
    private static double ScoreLabel(string label)
    {
        if (label.Length == 0) return 0;

        double bigram = Clamp01((BigramEnglishFloor - MeanLogBigram(label)) / (BigramEnglishFloor - BigramRandomFloor));
        double entropy = Clamp01((Entropy(label) - 3.0) / 1.20);
        double consonant = Clamp01((LongestConsonantRun(label) - 3) / 3.0);
        double digit = Clamp01((DigitRatio(label) - 0.10) / 0.30);
        double length = Clamp01((label.Length - 7) / 5.0);

        return Clamp01((0.42 * bigram) + (0.14 * entropy) + (0.14 * consonant) + (0.14 * digit) + (0.16 * length));
    }

    /// <summary>
    /// Mean base-10 log of the per-100,000 frequency of each adjacent letter pair.
    /// Pairs involving a digit or hyphen are skipped entirely. When a label contains no
    /// letter pair at all (<c>1234567</c>) the English floor is returned, i.e. the signal
    /// is withheld rather than guessed -- charging a numeric label for "unpronounceability"
    /// would be scoring the absence of evidence.
    /// </summary>
    private static double MeanLogBigram(string label)
    {
        double sum = 0;
        int pairs = 0;
        for (int i = 0; i + 1 < label.Length; i++)
        {
            char a = label[i], b = label[i + 1];
            if ((a is < 'a' or > 'z') || (b is < 'a' or > 'z')) continue;
            double w = Bigrams[((a - 'a') * 26) + (b - 'a')];
            if (w <= 0) w = MissingBigramWeight;
            sum += Math.Log10(w);
            pairs++;
        }
        return pairs == 0 ? BigramEnglishFloor : sum / pairs;
    }

    /// <summary>
    /// Shannon entropy in bits per character over the label's own symbol distribution.
    /// ASCII is counted in a stack buffer because that is the overwhelmingly common case
    /// on the DNS hot path; non-ASCII (raw UTF-8 in a query name, which does occur) falls
    /// back to a dictionary rather than being dropped, since dropping it would understate
    /// the entropy of exactly the names an attacker would craft.
    /// </summary>
    private static double Entropy(string s)
    {
        if (s.Length == 0) return 0;

        Span<int> ascii = stackalloc int[128];
        Dictionary<char, int>? wide = null;
        foreach (char c in s)
        {
            if (c < 128) { ascii[c]++; continue; }
            wide ??= new Dictionary<char, int>();
            wide.TryGetValue(c, out int seen);
            wide[c] = seen + 1;
        }

        double h = 0, total = s.Length;
        for (int i = 0; i < 128; i++)
        {
            if (ascii[i] == 0) continue;
            double p = ascii[i] / total;
            h -= p * Math.Log2(p);
        }
        if (wide is not null)
        {
            foreach (int n in wide.Values)
            {
                double p = n / total;
                h -= p * Math.Log2(p);
            }
        }
        return h;
    }

    /// <summary>
    /// Consonants over letters. Y is counted as a VOWEL: treating it as a consonant makes
    /// ordinary words such as "rhythm" and "syzygy" register long consonant runs, and the
    /// resulting false positives cost more than the handful of DGA labels that pad with y.
    /// </summary>
    private static double ConsonantRatio(string s)
    {
        int letters = 0, consonants = 0;
        foreach (char c in s)
        {
            if (c is < 'a' or > 'z') continue;
            letters++;
            if (!IsVowel(c)) consonants++;
        }
        return letters == 0 ? 0 : (double)consonants / letters;
    }

    private static double DigitRatio(string s)
    {
        if (s.Length == 0) return 0;
        int digits = 0;
        foreach (char c in s) if (c is >= '0' and <= '9') digits++;
        return (double)digits / s.Length;
    }

    private static int LongestConsonantRun(string s)
    {
        int best = 0, run = 0;
        foreach (char c in s)
        {
            if ((c is >= 'a' and <= 'z') && !IsVowel(c)) { run++; if (run > best) best = run; }
            else run = 0;   // vowels, digits and hyphens all break a run
        }
        return best;
    }

    private static bool IsVowel(char c) => c is 'a' or 'e' or 'i' or 'o' or 'u' or 'y';

    /// <summary>
    /// Shape test for data exfiltrated inside DNS queries (iodine, dnscat2, and the
    /// hand-rolled encoders in commodity loaders). Tunnels must pack payload bytes into
    /// labels, which forces one of: an unusually long left-most label, a base32/hex-looking
    /// left-most label, high entropy in the left-most label, or many long labels.
    ///
    /// This is shape only. It cannot distinguish a tunnel from the several legitimate
    /// systems with the same shape: cloud antivirus reputation lookups (which encode file
    /// hashes), DKIM selectors and key records, ACME dns-01 challenges, DNSBL queries that
    /// embed an address, and NSEC3 hashed names in a signed zone. Expect those in the
    /// results and allow-list them per environment.
    ///
    /// Implemented with linear character scans rather than regular expressions so a hostile
    /// multi-kilobyte label cannot trigger catastrophic backtracking.
    /// </summary>
    private static bool LooksLikeTunnel(string[] labels, int suffixLabels, out string why)
    {
        why = "";
        string left = labels[0];

        if (left.Length >= 40)
        {
            why = $"left-most label is {left.Length} characters, far past what human-chosen names use; consistent with DNS tunnelling";
            return true;
        }

        if (left.Length >= 24 && (IsBase32Like(left) || IsHexLike(left)))
        {
            why = $"left-most label is a {left.Length}-character base32/hex-looking blob; consistent with an encoded DNS tunnel payload";
            return true;
        }

        if (left.Length >= 20)
        {
            double h = Entropy(left);
            if (h >= 3.6)
            {
                why = $"left-most label is {left.Length} characters at {h.ToString("0.00", CultureInfo.InvariantCulture)} bits/char; consistent with encoded data in DNS";
                return true;
            }
        }

        int operatorLabels = Math.Max(0, labels.Length - suffixLabels - 1);
        if (labels.Length >= 7)
        {
            int payload = 0;
            for (int i = 0; i < operatorLabels; i++) payload += labels[i].Length;
            if (payload >= 60)
            {
                why = $"{labels.Length} labels carrying {payload} characters beneath the registrable domain; consistent with chunked DNS tunnelling";
                return true;
            }
        }
        return false;
    }

    /// <summary>RFC 4648 base32 alphabet (lower-cased), optionally padded. Linear scan, no regex.</summary>
    private static bool IsBase32Like(string s)
    {
        int body = s.Length;
        while (body > 0 && s[body - 1] == '=') body--;
        if (body == 0) return false;
        bool sawDigit = false;
        for (int i = 0; i < body; i++)
        {
            char c = s[i];
            if (c is >= 'a' and <= 'z') continue;
            if (c is >= '2' and <= '7') { sawDigit = true; continue; }
            return false;
        }
        // Require at least one 2-7 digit: a pure a-z string is far more likely to be words
        // than base32, and calling every long alphabetic label base32 would be useless.
        return sawDigit;
    }

    private static bool IsHexLike(string s)
    {
        bool sawDigit = false, sawAlpha = false;
        foreach (char c in s)
        {
            if (c is >= '0' and <= '9') { sawDigit = true; continue; }
            if (c is >= 'a' and <= 'f') { sawAlpha = true; continue; }
            return false;
        }
        // Both classes required, for the same reason as base32: "deadbeef" style content
        // needs digits to be hex rather than an English-ish word.
        return sawDigit && sawAlpha;
    }

    private static double Clamp01(double v) => v < 0 ? 0 : v > 1 ? 1 : v;

    private static double[] BuildBigrams()
    {
        var table = new double[26 * 26];
        foreach (var token in BigramTable.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (token.Length < 3) continue;
            char a = token[0], b = token[1];
            if (a is < 'a' or > 'z' || b is < 'a' or > 'z') continue;
            if (!int.TryParse(token.AsSpan(2), NumberStyles.None, CultureInfo.InvariantCulture, out int weight)) continue;
            table[((a - 'a') * 26) + (b - 'a')] = weight;
        }
        return table;
    }
