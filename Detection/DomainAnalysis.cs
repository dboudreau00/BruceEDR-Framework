using System.Globalization;
using System.Net;

namespace BruceEDR.Detection;

/// <summary>
/// Everything the heuristics concluded about one DNS name. All ratios are in 0..1 and
/// all values are finite, so the record survives <c>System.Text.Json</c> unchanged.
/// </summary>
public sealed record DomainVerdict
{
    /// <summary>The normalised name that was analysed: trimmed, lower-cased, root dot removed.</summary>
    public string Domain { get; init; } = "";

    /// <summary>0..1 composite DGA likelihood. See <see cref="DomainAnalysis"/> for the weights.</summary>
    public double DgaScore { get; init; }

    /// <summary>True when <see cref="DgaScore"/> clears the threshold on a long enough label.</summary>
    public bool LikelyDga { get; init; }

    /// <summary>The name sits under a known dynamic-DNS or tunnelling provider.</summary>
    public bool IsDynamicDns { get; init; }

    /// <summary>At least one label is IDNA-encoded (<c>xn--</c>), so homograph spoofing is possible.</summary>
    public bool IsPunycode { get; init; }

    /// <summary>Number of dot-separated labels in the whole name.</summary>
    public int LabelCount { get; init; }

    /// <summary>Shannon entropy, in bits per character, of the label that was scored.</summary>
    public double Entropy { get; init; }

    /// <summary>Consonants divided by letters in the scored label. Y counts as a vowel here.</summary>
    public double ConsonantRatio { get; init; }

    /// <summary>Digits divided by total characters in the scored label.</summary>
    public double DigitRatio { get; init; }

    /// <summary>Name plus public suffix, e.g. <c>example.co.uk</c>. Best-effort; see the class remarks.</summary>
    public string RegistrableDomain { get; init; } = "";

    /// <summary>Right-most label. Empty for an empty or non-domain input.</summary>
    public string Tld { get; init; } = "";

    /// <summary>Analyst-facing summary naming the signals that fired, or why none did.</summary>
    public string Explanation { get; init; } = "";

    /// <summary>Shape consistent with data smuggled through DNS labels. Heuristic; see remarks.</summary>
    public bool LooksLikeDnsTunnel { get; init; }
}

/// <summary>
/// Static, offline, allocation-light heuristics over DNS names: domain-generation
/// algorithm (DGA) scoring, dynamic-DNS provider recognition and DNS-tunnelling shape
/// detection. Ships every table inline -- nothing here downloads, resolves or touches
/// the network, so it runs identically on an air-gapped host and in a unit test.
///
/// HONEST ACCURACY STATEMENT. This is a heuristic and it has a real false-positive rate.
/// It has no allow-list of popular domains (shipping one would be a stale, jurisdiction-
/// biased blob), so the following classes of perfectly legitimate name score higher than
/// they should and WILL generate noise if wired straight to a blocking action:
///   * CDN and cloud-generated hostnames. CloudFront distributions (<c>d111111abcdef8</c>),
///     Azure blob and Front Door endpoints, S3 bucket names with build hashes, and
///     Fastly/Akamai edge names are machine-generated by design.
///   * Content-addressed infrastructure: IPFS gateways, container registries and
///     anything that puts a digest in a hostname.
///   * Non-English brands and transliterations. The bigram table is English; a Polish,
///     Turkish or romanised Japanese name looks "unpronounceable" to it and is penalised
///     unfairly. This is a genuine bias, not a rounding error.
///   * Security products themselves. Cloud AV reputation lookups encode file hashes into
///     DNS labels, so an endpoint agent's own traffic is shape-identical to DNS tunnelling.
/// Treat a positive as a lead to enrich, never as a verdict.
///
/// EVASION. A dictionary DGA (concatenating real words, as Suppobox and Matsnu do) scores
/// low here by construction, because its bigram statistics ARE English. Short labels carry
/// too little signal to judge at all and are gated out. None of this looks at registration
/// age, NXDOMAIN rates, or resolved-IP reputation, which is where the strong signal for
/// DGA actually lives.
/// </summary>
public static class DomainAnalysis
{
